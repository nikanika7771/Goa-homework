# The output should be two capital letters with a dot separating them.

# It should look like this:

# Sam Harris => S.H

# patrick feeney => P.F


def abbrev_name(name):
    words = name.split()
    return words [0] [0] .upper() + "."  +  words [1] [0].upper()


